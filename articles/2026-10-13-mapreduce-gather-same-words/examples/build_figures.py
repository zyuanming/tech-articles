for k,caption in enumerate(['较远的机器','已有输入副本的机器']):
 x=55+k*480;box(d,(x,190,x+405,445),fill='white');txt(d,x+202,237,caption,37,b=True,anchor='mm')
 if k==1:
  box(d,(x+55,290,x+345,400),'输入A + map',fill='#def1eb',size=40,color='#137f73')
 else:box(d,(x+65,290,x+335,400),'闲置worker',fill='#e9edef',size=40)
arrow(d,(780,480),(780,575),'#137f73');txt(d,65,610,'先本地读取；按键聚集时仍可能走网络。',38,b=True)
save(im,'20-data-locality','说明输入就近处理与后续shuffle是两项不同的数据移动。')

# Independent cover.
im,d=canvas('一百台机器，怎样数对一堆词？',560)
txt(d,55,125,'MapReduce：难处藏在“凑到一起”',40,MUTED)
for k,w in enumerate(['cat','dog','cat','bird']):token(d,50+k*235,240,w,1,w=210)
for k in [0,2]:arrow(d,(155+k*235,335),(500,405),C['cat'])
box(d,(335,415,665,510),'cat → 2',fill=L['cat'],outline=C['cat'],color=C['cat'],size=47)
im.save(P/'cover.png')
