"""Render original diagrams and an explicitly labelled program-output card.
Requires Pillow; reads results.json generated by wordcount.py. No network.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import json, math
P=Path(__file__).resolve().parents[1]; A=P/'assets'
R=json.loads((P/'examples/results.json').read_text())
W=1000
BG='#f8f6ef'; INK='#193640'; MUTED='#46616a'; LINE='#bccbcb'
C={'cat':'#d46b2b','dog':'#286bb0','bird':'#137f73','fish':'#7954a2'}
L={'cat':'#fdebdc','dog':'#e3effb','bird':'#def1eb','fish':'#eee6f5'}
FONT='/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc'
BOLD='/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc'
metrics=[]
def f(size=40,b=False): return ImageFont.truetype(BOLD if b else FONT,size,index=2)
def canvas(title,h=650,sub=None):
 im=Image.new('RGB',(W,h),BG);d=ImageDraw.Draw(im)
 d.rectangle((0,0,14,h),fill='#d46b2b'); d.text((48,30),title,font=f(52,True),fill=INK)
 if sub:d.text((48,108),sub,font=f(37),fill=MUTED)
 return im,d

def txt(d,x,y,s,size=40,fill=INK,b=False,anchor=None):
 d.text((x,y),str(s),font=f(size,b),fill=fill,anchor=anchor)

def box(d,xy,text=None,fill='white',outline=LINE,r=20,size=40,color=INK):
 d.rounded_rectangle(xy,r,fill=fill,outline=outline,width=2)
 if text is not None:
  x1,y1,x2,y2=xy;txt(d,(x1+x2)/2,(y1+y2)/2,text,size,color,True,'mm')

def arrow(d,a,b,color=INK,width=6):
 d.line([a,b],fill=color,width=width);an=math.atan2(b[1]-a[1],b[0]-a[0]);ll=18
 d.polygon([b,(b[0]-ll*math.cos(an-.5),b[1]-ll*math.sin(an-.5)),(b[0]-ll*math.cos(an+.5),b[1]-ll*math.sin(an+.5))],fill=color)

def token(d,x,y,word,count=None,w=165,h=76,size=40):
 box(d,(x,y,x+w,y+h),word if count is None else f'{word}, {count}',L[word],C[word],size=size,color=C[word])

def save(im,name,role):
 path=A/(name+'.png');im.save(path);metrics.append(dict(file='assets/'+path.name,size=list(im.size),minimum_key_font_px=37,effective_min_at_354=round(37*354/1000,2),role=role))

# 1. Input strip is the stable reference used by all subsequent diagrams.
im,d=canvas('只有这12个词',580,'A、B、C是三份输入；空格分开词。')
for j,(name,line) in enumerate(R['corpus'].items()):
 y=195+j*115;box(d,(48,y,142,y+78),name,fill='#193640',size=43,color='white')
 for k,w in enumerate(line.split()):token(d,175+k*195,y,w,w=170)
save(im,'01-corpus','逐词显示完整输入和文档身份，供全篇复算。')

# 2. Count result directly generated from data.
im,d=canvas('先把正确答案放在这里',650,'一格代表一次出现。')
for j,w in enumerate(('cat','dog','bird','fish')):
 y=190+j*105;txt(d,55,y+18,w,44,C[w],True)
 for k in range(R['base']['output'][w]):box(d,(220+k*115,y,315+k*115,y+70),fill=C[w],outline=C[w],r=12)
 txt(d,860,y+12,R['base']['output'][w],50,C[w],True)
save(im,'02-baseline','以可数格子建立单机基准，不先引入术语。')

# 3. Concrete map step.
im,d=canvas('map：看见一次，记下一对',640,'键 = 用来归类的词；值 = 此次贡献。')
box(d,(55,190,945,285),'A:  cat  dog  cat  bird',fill='white',size=45)
arrow(d,(500,310),(500,383))
for k,w in enumerate(R['corpus']['A'].split()):token(d,55+k*235,405,w,1,w=210,size=42)
txt(d,60,535,'两次 cat 要留下两份贡献。',42,b=True)
save(im,'03-map-one','用A说明一个输入记录可产生多个键值对，重复词不丢。')

# 4. Full intermediate stage.
im,d=canvas('三个任务各自做同一件事',670,'此时同一个词还散落在不同任务里。')
for j,(name,pairs) in enumerate(R['base']['mapped'].items()):
 y=200+j*128;txt(d,47,y+20,name,44,b=True)
 for k,(w,v) in enumerate(pairs):token(d,140+k*212,y,w,v,w=192,size=40)
save(im,'04-mapped-all','完整列出12对并保留来源，避免跨阶段凭空出现数据。')

# 5. Route and grouping distinction.
im,d=canvas('先约定：每个词去哪个分区？',660,'教学路由表；R0、R1、R2是任务编号。')
for j,(w,r) in enumerate([('cat',0),('dog',1),('bird',2),('fish',2)]):
 y=200+j*100;token(d,65,y,w,w=210);arrow(d,(300,y+38),(570,y+38),C[w]);box(d,(620,y,915,y+76),f'R{r}',fill=L[w],outline=C[w],color=C[w],size=43)
save(im,'05-route','显示同键同分区，同时bird和fish共享一个分区。')

# 6. Cat transport - independently designed tree (not paper figure).
im,d=canvas('shuffle：把散开的 cat 聚到一起',850,'R0向三个map结果取数据；只画cat路线。')
for k,(name,count) in enumerate([('A',2),('B',1),('C',2)]):
 x=50+k*315;box(d,(x,195,x+270,395),fill='white');txt(d,x+135,235,f'{name} 的本地结果',38,b=True,anchor='mm')
 txt(d,x+135,320,'cat: '+','.join('1' for _ in range(count)),40,C['cat'],True,'mm')
 arrow(d,(x+135,415),(500,590),C['cat'],6)
box(d,(85,620,915,775),fill=L['cat'],outline=C['cat']);txt(d,500,660,'R0 收齐三个来源',42,C['cat'],True,'mm');txt(d,500,720,'cat → [1, 1, 1, 1, 1]',43,C['cat'],True,'mm')
save(im,'06-shuffle-cat','把cat的跨机器收集单独展开，不用全连接杂乱箭头。')

# 7. Sort/group distinction.
im,d=canvas('同一个分区，还要再按键归组',740,'R2负责两个词，不能把四个1混成一组。')
for k,w in enumerate(['bird','fish','bird','fish']):token(d,55+k*235,190,w,1,w=210)
arrow(d,(500,305),(500,382))
for j,w in enumerate(['bird','fish']):
 y=425+j*135;box(d,(65,y,935,y+105),fill=L[w],outline=C[w]);txt(d,110,y+27,f'{w} → [1, 1]',45,C[w],True);txt(d,675,y+30,'单独一组',40,C[w])
save(im,'07-group-within-partition','纠正一个reduce任务只管一个键的误解，展示组边界。')

# 8. Sum with provenance.
im,d=canvas('reduce：现在才把同一组加起来',690,'cat 的五次出现 = A两次 + B一次 + C两次。')
for i,(nm,vals) in enumerate([('A',[1,1]),('B',[1]),('C',[1,1])]):
 x=60+i*310;box(d,(x,200,x+260,405),fill='white');txt(d,x+130,245,nm,43,b=True,anchor='mm');txt(d,x+130,330,' + '.join(map(str,vals)),48,C['cat'],True,'mm')
arrow(d,(500,435),(500,500));box(d,(190,530,810,625),'cat = 2 + 1 + 2 = 5',fill=L['cat'],outline=C['cat'],color=C['cat'],size=44)
save(im,'08-reduce-cat','将来源、数值与最终计数连接起来，算式可手查。')

# 9. Output files not global sort.
im,d=canvas('结果可以留在三份文件里',650,'按分区保存，不等于全局字典排序。')
for k,(nm,rows) in enumerate([('R0',['cat  5']),('R1',['dog  3']),('R2',['bird  2','fish  2'])]):
 x=50+k*315;box(d,(x,195,x+275,535),fill='white');txt(d,x+137,240,nm+' 输出',41,b=True,anchor='mm')
 for j,row in enumerate(rows):txt(d,x+137,330+j*95,row,43,anchor='mm')
save(im,'09-output-files','明确输出多文件及其局部键序，避免假设最终自动合并排序。')

# 10. Control/data roles.
im,d=canvas('调度者管进度，不包揽搬运',850,'实线：中间数据　虚线：任务与位置消息')
box(d,(290,190,710,295),'调度者 master',fill='#193640',size=43,color='white')
box(d,(55,515,445,685),'map worker',size=43);box(d,(560,515,950,685),'reduce worker',size=41)
for a,b in [((395,310),(220,490)),((620,310),(760,490))]:
 for q in range(0,10,2):
  aa=(a[0]+(b[0]-a[0])*q/10,a[1]+(b[1]-a[1])*q/10);bb=(a[0]+(b[0]-a[0])*(q+1)/10,a[1]+(b[1]-a[1])*(q+1)/10);d.line([aa,bb],fill=MUTED,width=5)
arrow(d,(450,610),(545,610),'#d46b2b',8);txt(d,55,735,'worker：执行任务的工作程序。',40)
save(im,'10-control-data','区分调度控制和数据路径，避免主节点汇聚所有词的错误模型。')

# 11. Tasks / workers.
im,d=canvas('任务是工作包，机器可以接下一包',660,'示意：6个任务，由2个worker先后执行。')
for j,work in enumerate([['M0','M2','M4'],['M1','M3','M5']]):
 y=205+j*190;txt(d,45,y+30,f'机器{j+1}',43,b=True)
 for k,name in enumerate(work):
  x=260+k*235;box(d,(x,y,x+175,y+110),name,fill=['#e3effb','#def1eb'][j],size=43)
  if k<2:arrow(d,(x+183,y+55),(x+225,y+55))
txt(d,240,570,'时间向右；任务数不等于机器数。',37)
save(im,'11-task-machine','用排班而非固定一一对应解释任务粒度。')

# 12. Lost map output and rerun.
im,d=canvas('机器掉线，算完的中间结果也可能丢',960,'以下对应2004年论文的本地中间文件设计。')
box(d,(65,190,935,355),fill='white');txt(d,100,222,'原输入A仍可从可用副本读取',40,b=True);txt(d,100,287,'cat dog cat bird',44)
arrow(d,(500,375),(500,450));box(d,(65,480,445,660),fill='#fbe7e6',outline='#b74d45');txt(d,255,530,'旧机器离线',43,'#b74d45',True,'mm');txt(d,255,600,'A 的中间文件不可取',37,'#b74d45',False,'mm')
box(d,(555,480,935,660),fill='#def1eb',outline='#137f73');txt(d,745,530,'换机器重跑A',43,'#137f73',True,'mm');txt(d,745,600,'重新产生4对',40,'#137f73',False,'mm')
arrow(d,(750,690),(750,750));txt(d,60,800,'通知尚未取数据的reduce改用新位置。',39,b=True)
save(im,'12-worker-failure','解释为何已经完成的map也可能需要重执行，附原输入可用前提。')

# 13. Duplicate attempt audit.
im,d=canvas('同一任务跑两次，不能当两份输入',850,'任务A固定；A.0、A.1是两次执行尝试。')
for j,(label,fill) in enumerate([('A.0 完整结果：cat2 dog1 bird1','#def1eb'),('A.1 完整结果：cat2 dog1 bird1','#e9edef')]):
 box(d,(65,195+j*150,935,310+j*150),label,fill=fill,size=39)
box(d,(65,540,935,645),'错误：两份都加 → cat7 dog4 bird3 fish2',fill='#fbe7e6',outline='#b74d45',size=37,color='#9b3933')
box(d,(65,685,935,790),'正确：A只贡献一次 → 5、3、2、2',fill='#def1eb',outline='#137f73',size=39,color='#137f73')
save(im,'13-duplicate-attempt','精确复算重复合并会多出哪些词，区分输入记录和执行尝试。')

# 14. Commit visibility.
im,d=canvas('先完成临时文件，再交出完整结果',690,'原子提交：读者不会看到半份最终文件。')
box(d,(65,195,440,440),fill='white');txt(d,250,247,'尝试自己的临时文件',37,b=True,anchor='mm');txt(d,250,330,'正在写……',43,anchor='mm')
arrow(d,(465,320),(535,320));box(d,(570,195,945,440),fill='#def1eb');txt(d,757,247,'最终输出位置',41,b=True,anchor='mm');txt(d,757,330,'一份完整结果',43,'#137f73',True,'mm')
txt(d,62,505,'重复发送邮件、扣款等外部动作，',40,b=True);txt(d,62,568,'不会因为文件提交而自动撤销。',40,b=True)
save(im,'14-commit-boundary','将输出提交保证和外部副作用分开，不许诺物理恰好执行一次。')

# 15. Timeline precise model.
im,d=canvas('慢任务：让备用尝试和原任务赛跑',780,'教学时间线，单位秒；不是集群跑分。')
x0=230;unit=82
for tick in [0,3,5,8]:
 x=x0+tick*unit;d.line((x,200,x,575),fill=LINE,width=2);txt(d,x,625,tick,40,anchor='mm')
for y,label,start,end,col in [(280,'原尝试',0,8,'#d46b2b'),(435,'备用尝试',3,5,'#137f73')]:
 txt(d,55,y+8,label,39,b=True);box(d,(x0+start*unit,y,x0+end*unit,y+65),fill=col,outline=col,r=10)
txt(d,50,705,'3秒启动备用；5秒采用先完成的结果。',39,b=True)
save(im,'15-straggler','时间轴明确备份开始、耗时和完成点，说明尾部等待。')

# 16. Hotspot compare on common axis raw pairs. Log not used.
im,d=canvas('热点：数据本身挤向同一个键',870,'只在A后追加100个cat；横轴是键值对数。')
for j,(label,vals) in enumerate([('原语料',[5,3,4]),('追加后',[105,3,4])]):
 y=205+j*305;txt(d,55,y,label,42,b=True)
 for k,(n,col) in enumerate(zip(vals,[C['cat'],C['dog'],C['bird']])):
  yy=y+70+k*62;txt(d,75,yy,f'R{k}',38,b=True);d.rectangle((200,yy+8,200+n*6,yy+45),fill=col);txt(d,220+n*6,yy,str(n),38,col,True)
save(im,'16-hot-key','用相同刻度展示5/3/4变105/3/4，区分偏斜和慢机器。')

# 17. Combiner quantities exact.
im,d=canvas('combiner：上路前先做小计',860,'仍用原来的12个词；这里每个map合并一次。')
for j,(name,parts) in enumerate(R['combined']['sent'].items()):
 y=200+j*145;txt(d,50,y+20,name,43,b=True)
 for k,(w,n) in enumerate(parts):token(d,145+k*275,y,w,n,w=245,size=42)
box(d,(65,680,935,795),'发送12对 → 9对；数值总和仍是12',fill='#def1eb',size=41,color='#137f73')
save(im,'17-combiner','完整展示9个小计及保持的数值总和，不混淆条数与计数。')

# 18. Mean counterexample; clear optional transfer example.
im,d=canvas('不是所有“小计”都能直接再平均',940,'另一个反例：两批数的条数不一样。')
box(d,(60,190,940,315),'A：[4]　平均值4，只有1条',fill='#e3effb',size=43)
box(d,(60,350,940,475),'B：[1,1,1,1,1]　平均值1，共5条',fill='#def1eb',size=39)
